import fs from 'node:fs';
import path from 'node:path';

import {
  AndroidConfig,
  type ConfigPlugin,
  withAndroidManifest,
  withDangerousMod,
} from 'expo/config-plugins';

/**
 * Puts the app in Android's Share sheet for plain text. A small activity receives the text and
 * hands it to MainActivity as a `<scheme>://shared-text?text=…` link, which opens Find words in
 * text. Like opened pack files, the text arrives in the app's own task, so only one copy of the
 * app runs. No permission is needed.
 */

export const SHARED_TEXT_ACTIVITY_NAME = 'SharedTextActivity';

// Expo loads a plugin file on its own, so it can't import the app's TypeScript. These match
// SHARED_TEXT_LINK_HOST and MAX_SEARCHED_TEXT_LENGTH in src/services; a test checks they agree.
export const SHARED_TEXT_HOST = 'shared-text';
export const MAX_SHARED_TEXT_LENGTH = 1000;

type ManifestActivity = AndroidConfig.Manifest.ManifestActivity;
type AndroidManifest = AndroidConfig.Manifest.AndroidManifest;

const SEND_ACTION = 'android.intent.action.SEND';
const DEFAULT_CATEGORY = 'android.intent.category.DEFAULT';
const PLAIN_TEXT_MIME_TYPE = 'text/plain';

export function sharedTextActivity(): ManifestActivity {
  return {
    $: {
      'android:name': `.${SHARED_TEXT_ACTIVITY_NAME}`,
      'android:exported': 'true',
      // No window, no history and no Recents entry: the activity only forwards the text.
      'android:theme': '@android:style/Theme.NoDisplay',
      'android:noHistory': 'true',
      'android:excludeFromRecents': 'true',
    },
    'intent-filter': [
      {
        action: [{ $: { 'android:name': SEND_ACTION } }],
        category: [{ $: { 'android:name': DEFAULT_CATEGORY } }],
        data: [{ $: { 'android:mimeType': PLAIN_TEXT_MIME_TYPE } }],
      },
    ],
  };
}

/** Adds the activity, replacing any copy from an earlier run so prebuild stays repeatable. */
export function addSharedTextActivity(manifest: AndroidManifest): AndroidManifest {
  const application = AndroidConfig.Manifest.getMainApplicationOrThrow(manifest);
  const otherActivities = (application.activity ?? []).filter(
    (activity) => activity.$['android:name'] !== `.${SHARED_TEXT_ACTIVITY_NAME}`,
  );
  application.activity = [...otherActivities, sharedTextActivity()];
  return manifest;
}

export function sharedTextActivitySource(packageName: string, scheme: string): string {
  return `package ${packageName}

import android.app.Activity
import android.content.Intent
import android.net.Uri
import android.os.Bundle

// Generated by plugins/withSharedTextActivity.ts. Hands text shared from another app to
// MainActivity as a link, in the app's own task.
private const val MAX_SHARED_TEXT_LENGTH = ${MAX_SHARED_TEXT_LENGTH}

// Shared text comes from any app, so only its start is passed on (whole characters only).
private fun firstCharacters(text: String, count: Int): String {
  if (text.codePointCount(0, text.length) <= count) return text
  return text.substring(0, text.offsetByCodePoints(0, count))
}

class ${SHARED_TEXT_ACTIVITY_NAME} : Activity() {
  override fun onCreate(savedInstanceState: Bundle?) {
    super.onCreate(savedInstanceState)
    val sharedText = intent.getCharSequenceExtra(Intent.EXTRA_TEXT)?.toString().orEmpty().trim()
    val forward = Intent(this, MainActivity::class.java)
    if (sharedText.isNotEmpty()) {
      forward.action = Intent.ACTION_VIEW
      forward.data = Uri.Builder()
        .scheme("${scheme}")
        .authority("${SHARED_TEXT_HOST}")
        .appendQueryParameter("text", firstCharacters(sharedText, MAX_SHARED_TEXT_LENGTH))
        .build()
    }
    forward.addFlags(Intent.FLAG_ACTIVITY_NEW_TASK)
    startActivity(forward)
    finish()
  }
}
`;
}

function writeActivitySource(projectRoot: string, packageName: string, scheme: string): void {
  const packageDirectory = path.join(
    projectRoot,
    'app',
    'src',
    'main',
    'java',
    ...packageName.split('.'),
  );
  fs.mkdirSync(packageDirectory, { recursive: true });
  fs.writeFileSync(
    path.join(packageDirectory, `${SHARED_TEXT_ACTIVITY_NAME}.kt`),
    sharedTextActivitySource(packageName, scheme),
  );
}

export const withSharedTextActivity: ConfigPlugin = (config) => {
  const packageName = config.android?.package;
  const scheme = typeof config.scheme === 'string' ? config.scheme : undefined;
  if (!packageName || !scheme) {
    throw new Error('withSharedTextActivity needs android.package and scheme in app.json');
  }
  const withManifest = withAndroidManifest(config, (modConfig) => {
    modConfig.modResults = addSharedTextActivity(modConfig.modResults);
    return modConfig;
  });
  return withDangerousMod(withManifest, [
    'android',
    (modConfig) => {
      writeActivitySource(modConfig.modRequest.platformProjectRoot, packageName, scheme);
      return modConfig;
    },
  ]);
};
export default withSharedTextActivity;
