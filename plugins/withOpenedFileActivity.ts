import fs from 'node:fs';
import path from 'node:path';

import {
  AndroidConfig,
  type ConfigPlugin,
  withAndroidManifest,
  withDangerousMod,
} from 'expo/config-plugins';

/**
 * Language pack files opened from other apps (route B) arrive at a small activity of their own
 * instead of MainActivity. Files by Google on Android 17 starts the receiving activity inside its
 * own task and ignores MainActivity's singleTask, which left a second copy of the app running
 * there. The small activity hands the file to MainActivity as a new task and closes, so only one
 * copy of the app ever runs.
 */

export const OPENED_FILE_ACTIVITY_NAME = 'OpenedFileActivity';

type ManifestActivity = AndroidConfig.Manifest.ManifestActivity;
type ManifestIntentFilter = AndroidConfig.Manifest.ManifestIntentFilter;
type AndroidManifest = AndroidConfig.Manifest.AndroidManifest;

const VIEW_ACTION = 'android.intent.action.VIEW';
const DEFAULT_CATEGORY = 'android.intent.category.DEFAULT';
const OPENED_FILE_SCHEMES = ['content', 'file'];
const DOWNLOAD_MIME_TYPE = 'application/octet-stream';
// Android's pathPattern needs a doubled backslash in the manifest to match a literal dot.
const PACK_PATH_PATTERN = '.*\\\\.mfpack';
// pathPattern stops at the first dot it can match, so a second pattern covers names with dots.
const PACK_PATH_PATTERN_EXTRA_DOT = '.*\\\\..*\\\\.mfpack';

function viewFilter(data: ManifestIntentFilter['data']): ManifestIntentFilter {
  return {
    action: [{ $: { 'android:name': VIEW_ACTION } }],
    category: [{ $: { 'android:name': DEFAULT_CATEGORY } }],
    data,
  };
}

/** Downloads usually arrive as octet-stream; some file apps only pass the .mfpack name. */
export function openedFileIntentFilters(): ManifestIntentFilter[] {
  const byMimeType = OPENED_FILE_SCHEMES.map((scheme) => ({
    $: { 'android:scheme': scheme, 'android:mimeType': DOWNLOAD_MIME_TYPE },
  }));
  const byFileName = OPENED_FILE_SCHEMES.map((scheme) => ({
    $: {
      'android:scheme': scheme,
      'android:host': '*',
      'android:mimeType': '*/*',
      'android:pathPattern': PACK_PATH_PATTERN,
    },
  }));
  const byFileNameWithDots = {
    $: {
      'android:scheme': 'file',
      'android:host': '*',
      'android:mimeType': '*/*',
      'android:pathPattern': PACK_PATH_PATTERN_EXTRA_DOT,
    },
  };
  return [viewFilter(byMimeType), viewFilter([...byFileName, byFileNameWithDots])];
}

export function openedFileActivity(): ManifestActivity {
  return {
    $: {
      'android:name': `.${OPENED_FILE_ACTIVITY_NAME}`,
      'android:exported': 'true',
      // No window, no history and no Recents entry: the activity only forwards the file.
      'android:theme': '@android:style/Theme.NoDisplay',
      'android:noHistory': 'true',
      'android:excludeFromRecents': 'true',
    },
    'intent-filter': openedFileIntentFilters(),
  };
}

/** Adds the activity, replacing any copy from an earlier run so prebuild stays repeatable. */
export function addOpenedFileActivity(manifest: AndroidManifest): AndroidManifest {
  const application = AndroidConfig.Manifest.getMainApplicationOrThrow(manifest);
  const otherActivities = (application.activity ?? []).filter(
    (activity) => activity.$['android:name'] !== `.${OPENED_FILE_ACTIVITY_NAME}`,
  );
  application.activity = [...otherActivities, openedFileActivity()];
  return manifest;
}

export function openedFileActivitySource(packageName: string): string {
  return `package ${packageName}

import android.app.Activity
import android.content.Intent
import android.os.Bundle

// Generated by plugins/withOpenedFileActivity.ts. Hands a file opened from another app to
// MainActivity in the app's own task, so the opening app's task never holds a copy of the app.
class ${OPENED_FILE_ACTIVITY_NAME} : Activity() {
  override fun onCreate(savedInstanceState: Bundle?) {
    super.onCreate(savedInstanceState)
    val forward = Intent(Intent.ACTION_VIEW, intent.data, this, MainActivity::class.java)
    // Passing the read grant on lets MainActivity read the file after this activity closes.
    forward.addFlags(Intent.FLAG_ACTIVITY_NEW_TASK or Intent.FLAG_GRANT_READ_URI_PERMISSION)
    startActivity(forward)
    finish()
  }
}
`;
}

function writeActivitySource(projectRoot: string, packageName: string): void {
  const packageDirectory = path.join(
    projectRoot,
    'app',
    'src',
    'main',
    'java',
    ...packageName.split('.'),
  );
  fs.mkdirSync(packageDirectory, { recursive: true });
  fs.writeFileSync(
    path.join(packageDirectory, `${OPENED_FILE_ACTIVITY_NAME}.kt`),
    openedFileActivitySource(packageName),
  );
}

export const withOpenedFileActivity: ConfigPlugin = (config) => {
  const packageName = config.android?.package;
  if (!packageName) throw new Error('withOpenedFileActivity needs android.package in app.json');
  const withManifest = withAndroidManifest(config, (modConfig) => {
    modConfig.modResults = addOpenedFileActivity(modConfig.modResults);
    return modConfig;
  });
  return withDangerousMod(withManifest, [
    'android',
    (modConfig) => {
      writeActivitySource(modConfig.modRequest.platformProjectRoot, packageName);
      return modConfig;
    },
  ]);
};
export default withOpenedFileActivity;
