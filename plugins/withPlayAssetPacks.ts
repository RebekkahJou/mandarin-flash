import fs from 'node:fs';
import path from 'node:path';

import {
  type ConfigPlugin,
  WarningAggregator,
  withAppBuildGradle,
  withDangerousMod,
  withSettingsGradle,
} from 'expo/config-plugins';

import storePackCatalog from '../src/domain/storePackCatalog.json';

/**
 * Puts each store pack (src/domain/storePackCatalog.json) into the Android app bundle as an on-demand Play
 * asset pack (route A): a Gradle module per pack holding its signed .mfpack file, listed in
 * settings.gradle and in the app's assetPacks. Only bundles (.aab) carry asset packs; APK builds
 * ignore them. Test packs are left out of release builds (RELEASE_BUILD=1), and a test pack whose
 * file hasn't been made is skipped with a warning.
 */

/** The catalog fields the build needs. Expo loads only this file as TypeScript, so the plugin
 * reads the JSON catalog directly instead of importing src/domain/storePacks.ts. */
export interface StorePack {
  assetPackName: string;
  sourcePath: string;
  fileName: string;
  isTestPack: boolean;
}

/** Play's rule for asset pack names. */
const ASSET_PACK_NAME_PATTERN = /^[A-Za-z][A-Za-z0-9_]*$/;
const BLOCK_START = '// @generated begin withPlayAssetPacks';
const BLOCK_END = '// @generated end withPlayAssetPacks';
const GENERATED_BLOCK = new RegExp(`\\n?${BLOCK_START}[\\s\\S]*?${BLOCK_END}\\n?`, 'g');
const ANDROID_BLOCK_OPENING = /^android \{\n/m;
const ASSET_PACK_FOLDER_ASSETS = path.join('src', 'main', 'assets');

function generatedBlock(lines: readonly string[]): string {
  return [BLOCK_START, ...lines, BLOCK_END].join('\n');
}

function withoutGeneratedBlock(contents: string): string {
  return contents.replace(GENERATED_BLOCK, '\n');
}

/** Replaces any block from an earlier run, so prebuild stays repeatable. */
export function addAssetPacksToSettings(
  contents: string,
  storePacks: readonly StorePack[],
): string {
  const cleaned = withoutGeneratedBlock(contents).trimEnd();
  if (storePacks.length === 0) return `${cleaned}\n`;
  const includes = storePacks.map((storePack) => `include ':${storePack.assetPackName}'`);
  return `${cleaned}\n\n${generatedBlock(includes)}\n`;
}

export function addAssetPacksToAppBuild(
  contents: string,
  storePacks: readonly StorePack[],
): string {
  const cleaned = withoutGeneratedBlock(contents);
  if (storePacks.length === 0) return cleaned;
  if (!ANDROID_BLOCK_OPENING.test(cleaned)) {
    throw new Error('withPlayAssetPacks could not find the android block in app/build.gradle');
  }
  const names = storePacks.map((storePack) => `":${storePack.assetPackName}"`).join(', ');
  const block = generatedBlock([`    assetPacks = [${names}]`]);
  return cleaned.replace(ANDROID_BLOCK_OPENING, (opening) => `${opening}${block}\n`);
}

export function assetPackBuildGradle(storePack: StorePack): string {
  return `// Generated by plugins/withPlayAssetPacks.ts.
plugins {
    id 'com.android.asset-pack'
}

assetPack {
    packName = "${storePack.assetPackName}"
    dynamicDelivery {
        deliveryType = "on-demand"
    }
}
`;
}

/** Store packs this build includes. A missing real pack file stops the build. */
export function storePacksToBundle(
  catalog: readonly StorePack[],
  projectRoot: string,
  isReleaseBuild: boolean,
  warn: (message: string) => void,
): StorePack[] {
  const forThisBuild = catalog.filter((storePack) => !isReleaseBuild || !storePack.isTestPack);
  return forThisBuild.filter((storePack) => {
    if (!ASSET_PACK_NAME_PATTERN.test(storePack.assetPackName)) {
      throw new Error(`"${storePack.assetPackName}" is not a valid asset pack name.`);
    }
    if (fs.existsSync(path.join(projectRoot, storePack.sourcePath))) return true;
    if (!storePack.isTestPack) throw new Error(`Store pack file missing: ${storePack.sourcePath}`);
    warn(`Skipping test store pack ${storePack.assetPackName}: ${storePack.sourcePath} not found.`);
    return false;
  });
}

function writeAssetPackModule(
  projectRoot: string,
  androidRoot: string,
  storePack: StorePack,
): void {
  const moduleRoot = path.join(androidRoot, storePack.assetPackName);
  fs.rmSync(moduleRoot, { recursive: true, force: true });
  const assetsFolder = path.join(moduleRoot, ASSET_PACK_FOLDER_ASSETS);
  fs.mkdirSync(assetsFolder, { recursive: true });
  fs.writeFileSync(path.join(moduleRoot, 'build.gradle'), assetPackBuildGradle(storePack));
  fs.copyFileSync(
    path.join(projectRoot, storePack.sourcePath),
    path.join(assetsFolder, storePack.fileName),
  );
}

export const withPlayAssetPacks: ConfigPlugin = (config) => {
  const isReleaseBuild = process.env.RELEASE_BUILD === '1';
  let bundledPacks: StorePack[] | null = null;
  const packsFor = (projectRoot: string) => {
    bundledPacks ??= storePacksToBundle(storePackCatalog, projectRoot, isReleaseBuild, (message) =>
      WarningAggregator.addWarningAndroid('withPlayAssetPacks', message),
    );
    return bundledPacks;
  };
  const withSettings = withSettingsGradle(config, (modConfig) => {
    const storePacks = packsFor(modConfig.modRequest.projectRoot);
    modConfig.modResults.contents = addAssetPacksToSettings(
      modConfig.modResults.contents,
      storePacks,
    );
    return modConfig;
  });
  const withAppBuild = withAppBuildGradle(withSettings, (modConfig) => {
    const storePacks = packsFor(modConfig.modRequest.projectRoot);
    modConfig.modResults.contents = addAssetPacksToAppBuild(
      modConfig.modResults.contents,
      storePacks,
    );
    return modConfig;
  });
  return withDangerousMod(withAppBuild, [
    'android',
    (modConfig) => {
      const { projectRoot, platformProjectRoot } = modConfig.modRequest;
      for (const storePack of packsFor(projectRoot)) {
        writeAssetPackModule(projectRoot, platformProjectRoot, storePack);
      }
      return modConfig;
    },
  ]);
};
export default withPlayAssetPacks;
