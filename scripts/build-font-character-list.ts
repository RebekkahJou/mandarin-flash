/**
 * Chooses which characters the bundled fonts keep (run after build-mandarin-pack):
 *
 *   npm run build:font-characters
 *
 * Writes assets/fonts/subset-characters.txt (input for scripts/subset-fonts.py) and
 * src/services/generated/fontCharacters.ts (lets the app fall back to the system font
 * for any character outside the subset).
 */
import Database from 'better-sqlite3';
import { mkdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';

import { MANDARIN_PACK_PATH } from './lib/mandarinPack';

const ROOT = path.join(__dirname, '..');
const CHARACTER_LIST_PATH = path.join(ROOT, 'assets', 'fonts', 'subset-characters.txt');
const GENERATED_MODULE_PATH = path.join(ROOT, 'src', 'services', 'generated', 'fontCharacters.ts');
/** Covers everyday Taiwan text while keeping each subset font to a few MB. */
const SUBSET_CHARACTER_COUNT = 8000;
const SENTENCE_OCCURRENCE_WEIGHT = 5;
const HAN_CHARACTER = /\p{Script=Han}/u;

function countCharacters(
  texts: Iterable<string>,
  counts: Map<string, number>,
  weight: number,
): void {
  for (const text of texts) {
    for (const character of text) {
      if (HAN_CHARACTER.test(character)) {
        counts.set(character, (counts.get(character) ?? 0) + weight);
      }
    }
  }
}

function main(): void {
  const database = new Database(MANDARIN_PACK_PATH, { readonly: true });
  const words = database.prepare('SELECT headword FROM entries').pluck().all() as string[];
  const sentences = database.prepare('SELECT text FROM sentences').pluck().all() as string[];
  database.close();

  // A character that appears in many words and sentences is a common character.
  const counts = new Map<string, number>();
  countCharacters(words, counts, 1);
  countCharacters(sentences, counts, SENTENCE_OCCURRENCE_WEIGHT);
  const characters = [...counts.entries()]
    .sort((first, second) => second[1] - first[1])
    .slice(0, SUBSET_CHARACTER_COUNT)
    .map(([character]) => character)
    .join('');

  writeFileSync(CHARACTER_LIST_PATH, characters, 'utf8');
  mkdirSync(path.dirname(GENERATED_MODULE_PATH), { recursive: true });
  writeFileSync(
    GENERATED_MODULE_PATH,
    `// Generated by scripts/build-font-character-list.ts. Do not edit.\n` +
      `export const SUBSET_FONT_CHARACTERS = '${characters}';\n`,
    'utf8',
  );
  console.log(`Kept ${[...characters].length} characters.`);
}

main();
